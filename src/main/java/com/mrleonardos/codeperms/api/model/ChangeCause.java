package com.mrleonardos.codeperms.api.model;

/**
 * Причина правки прав. Её видно в событиях для слушателей и в аудите, поэтому по журналу всегда
 * понятно, кто и зачем поменял доступ.
 */
public enum ChangeCause {

    /** Правка из команды администратора. */
    COMMAND,

    /** Правка через API чужого мода. */
    API,

    /** Перенос прав из файла ядра. */
    IMPORT,

    /** Снятие истёкшей выдачи или ноды. */
    EXPIRY,

    /** Приведение хранилища к новой версии схемы. */
    MIGRATION
}
