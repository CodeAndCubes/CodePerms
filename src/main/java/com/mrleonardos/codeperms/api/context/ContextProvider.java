package com.mrleonardos.codeperms.api.context;

import java.util.Map;

import com.mrleonardos.codecore.api.actor.PlayerRef;

/**
 * Источник контекстов чужого мода.
 *
 * <p>
 * Провайдера регистрируют в {@code PermsApi.contexts()} на инициализации своего мода. Пары собираются
 * по событиям входа, смены измерения и респауна, а не на каждой проверке права, поэтому провайдер
 * должен отвечать быстро и без обращений к диску.
 */
public interface ContextProvider {

    /** Имя провайдера: им он регистрируется и снимается с регистрации. */
    String id();

    /**
     * Пары контекстов для игрока.
     *
     * <p>
     * Ссылка даёт идентификатор и ник, и почти всякому провайдеру этого хватает: клан, режим игры,
     * оплаченный статус ищут по идентификатору. Тому, кому нужен живой игрок (мир, измерение, позиция),
     * его отдаёт {@code PlayerRefs.online(subject)} из артефакта ядра с классификатором
     * {@code platform}. Зависимость на платформу объявляется явно тем, кому она правда нужна, а api
     * остаётся собираемым без единого типа игры.
     *
     * @param subject игрок, для которого собирают набор
     * @return пары контекстов; пустая карта или {@code null}, если провайдеру нечего добавить
     */
    Map<String, String> collect(PlayerRef subject);
}
